import { todayMatches } from '../app/src/provider-engine-v2.js';
import { analyzeMatch } from '../app/src/analysis-engine-v2.js';
const day=new Intl.DateTimeFormat('en-CA',{timeZone:'Europe/Rome',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
const fail=m=>{throw new Error(`FAIL: ${m}`)};
const assert=(v,m)=>{if(!v)fail(m)};
console.log(`VERIFY DAY ${day}`);
const matches=await todayMatches(day);
console.log(`FIXTURES ${matches.length}`);
console.log('SAMPLE PROVIDER ROWS',JSON.stringify(matches.slice(0,3).map(x=>({home:x.home,away:x.away,league:x.league,country:x.country,source:x.source,sofaEventId:x.sofaEventId,sofaTournamentId:x.sofaTournamentId,sofaSeasonId:x.sofaSeasonId}))));
assert(matches.length>=40,`Only ${matches.length} fixtures returned`);
assert(matches.every(x=>x.home&&x.away&&x.time&&x.eventId),'Fixture with missing team/time/event id');
assert(new Set(matches.map(x=>x.home+'|'+x.away+'|'+x.time)).size===matches.length,'Duplicate fixture rows');
const realCompetition=matches.filter(x=>x.league&&x.league!=='Altra competizione').length;
assert(realCompetition/matches.length>=0.95,`Only ${realCompetition}/${matches.length} fixtures have a competition label`);
const supported=matches.filter(x=>x.sofaIdHome&&x.sofaIdAway&&x.sofaEventId).slice(0,5);
assert(supported.length>=3,'Not enough fixtures with stable SofaScore IDs for analysis verification');
const analyzed=await Promise.all(supported.map(x=>analyzeMatch(x)));
for(const x of analyzed)console.log(`${x.home} vs ${x.away} | H2H=${x.h2hCount} | form=${x.H.form.length}/${x.A.form.length} | teamStats=${x.verifiedStats} | statFields=${x.statSamples}`);
assert(analyzed.every(x=>x.homeData.sofaId&&x.awayData.sofaId),'SofaScore team IDs missing');
assert(analyzed.every(x=>x.H.form.length>=2&&x.A.form.length>=2),'Recent team form was not recovered');
assert(analyzed.some(x=>x.h2hCount>0),'H2H returned zero meetings for every verification sample');
assert(analyzed.some(x=>x.verifiedStats>0),'No real team statistics recovered from SofaScore season endpoint');
assert(analyzed.some(x=>x.statSamples>=3),'Too few real statistical fields recovered');
console.log(`PASS: ${matches.length} fixtures + competitions + recent form + H2H + real team statistics.`);
