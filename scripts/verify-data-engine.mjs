import { todayMatches } from '../app/src/fixture-engine.js';
import { analyzeMatch } from '../app/src/analysis-engine.js';
const day=new Intl.DateTimeFormat('en-CA',{timeZone:'Europe/Rome',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
const fail=m=>{throw new Error(`FAIL: ${m}`)};
const assert=(v,m)=>{if(!v)fail(m)};
console.log(`VERIFY DAY ${day}`);
const matches=await todayMatches(day);
console.log(`FIXTURES ${matches.length}`);
assert(matches.length>=40,`Only ${matches.length} fixtures returned`);
assert(matches.every(x=>x.home&&x.away&&x.time&&x.eventId),'Fixture with missing team/time/event id');
assert(new Set(matches.map(x=>x.home+'|'+x.away+'|'+x.time)).size===matches.length,'Duplicate fixture rows');
const realCompetition=matches.filter(x=>x.league&&x.league!=='Altra competizione').length;
assert(realCompetition/matches.length>=0.95,`Only ${realCompetition}/${matches.length} fixtures have a competition label`);
const sample=matches.filter(x=>/russian-premier-league|saudi-pro-league/i.test(x.espnSeasonSlug||'')).slice(0,3);
assert(sample.length>=2,'Not enough supported league fixtures for historical verification');
const analyzed=await Promise.all(sample.map(x=>analyzeMatch(x)));
for(const x of analyzed)console.log(`${x.home} vs ${x.away} | ids=${x.homeData.espnId||'-'} | H2H=${x.h2hCount} | history=${x.H.form.length}/${x.A.form.length}`);
assert(analyzed.every(x=>x.homeData.espnId&&x.awayData.espnId),'ESPN team ID lookup failed');
assert(analyzed.every(x=>x.H.form.length>0&&x.A.form.length>0),'Historical team matches were not recovered');
assert(analyzed.some(x=>x.h2hCount>0),'H2H returned zero meetings for every supported sample');
console.log('PASS: full-day fixtures, competition labels, team history and automatic H2H are available.');
