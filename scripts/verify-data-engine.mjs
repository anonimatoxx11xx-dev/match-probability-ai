import { todayMatches } from '../app/src/fixture-engine.js';
import { analyzeMatch } from '../app/src/analysis-engine.js';
const day=new Intl.DateTimeFormat('en-CA',{timeZone:'Europe/Rome',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
const fail=m=>{throw new Error(`FAIL: ${m}`)};
const assert=(v,m)=>{if(!v)fail(m)};
console.log(`VERIFY DAY ${day}`);
const matches=await todayMatches(day);
console.log(`FIXTURES ${matches.length}`);
console.log('FIRST FIXTURES',matches.slice(0,10).map(x=>({source:x.source,league:x.league,home:x.home,away:x.away,sofa:Boolean(x.sofaIdHome&&x.sofaIdAway)})));
assert(matches.length>=40,`Only ${matches.length} fixtures returned`);
assert(matches.every(x=>x.home&&x.away&&x.time&&x.eventId),'Fixture with missing team/time/event id');
assert(new Set(matches.map(x=>x.home+'|'+x.away+'|'+x.time)).size===matches.length,'Duplicate fixture rows');
const sample=matches.slice(0,5);
const analyzed=await Promise.all(sample.map(x=>analyzeMatch(x)));
console.log('SAMPLE ANALYSIS');
for(const x of analyzed)console.log(`${x.home} vs ${x.away} | ids=${x.homeData.sofaId}/${x.awayData.sofaId} | H2H=${x.h2hCount} | history=${x.H.form.length}/${x.A.form.length} | statRows=${x.verifiedStats}`);
assert(analyzed.every(x=>x.homeData.sofaId&&x.awayData.sofaId),'Team ID lookup failed for a sampled fixture');
assert(analyzed.every(x=>x.H.form.length>0&&x.A.form.length>0),'A sampled team has no historical matches');
assert(analyzed.some(x=>x.h2hCount>0),'H2H returned zero meetings for every sampled fixture');
assert(analyzed.some(x=>x.verifiedStats>0),'No historical match statistics were recovered');
console.log('PASS: daily fixtures, team history, H2H and historical statistics are available.');
